import {writeFileSync} from "fs";
import {defineConfig, type Plugin} from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";

/**
 * `base: "./"` — emit relative asset paths in the built index.html, so the
 * same build works both:
 *   - when served from any URL prefix by GGApiDocs (it rewrites `./assets/`
 *     to the absolute mount path before serving)
 *   - when written out as a static site by buildApiDocs (no rewriting)
 *
 * Nothing is written to disk: the build is embedded into ../src/viewer.gen.ts,
 * so the package carries the UI as code and never has to locate files at runtime.
 */
export default defineConfig({
    plugins: [react(), tailwindcss(), embedViewer("../src/viewer.gen.ts")],
    base: "./",
    build: {write: false},
    server: {port: 5180, host: "127.0.0.1"},
});

function embedViewer(outFile: string): Plugin {
    return {
        name: "embed-viewer",
        apply: "build",
        enforce: "post",
        generateBundle(_options, bundle) {
            const files = Object.values(bundle)
                .map(f => [f.fileName, f.type === "chunk" ? f.code : typeof f.source === "string" ? f.source : new TextDecoder().decode(f.source)])
                .sort(([a], [b]) => a.localeCompare(b));
            writeFileSync(outFile, [
                "// Generated by ui/vite.config.ts — run `npx vite build` in ui/. Do not edit.",
                "export const viewerFiles: Record<string, string> = {",
                ...files.map(([name, body]) => `    ${JSON.stringify(name)}: ${JSON.stringify(body)},`),
                "};",
                "",
            ].join("\n"));
        },
    };
}
