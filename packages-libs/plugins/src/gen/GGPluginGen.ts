// Runs under plain `node` (type stripping): node:* imports only, no relative imports.
import {existsSync, readdirSync, readFileSync, writeFileSync} from "node:fs"
import {dirname, join, relative} from "node:path"
import {fileURLToPath, pathToFileURL} from "node:url"

export interface GGPluginGenLayer {
    /** The generated constant: `{[pluginName]: facet}`. */
    name: string
    /** Package subpaths searched for the facet, e.g. `"./hub-api-server"`; at most one may export it. */
    from: readonly string[]
    /** The facet's export name after the camel-cased plugin name: `"HubPlugin"` → `secretsHubPlugin`. */
    export: string
    /** Output file, relative to `root`. Layers that share one are written together. */
    out: string
}

export interface GGPluginGenConfig {
    /** Repo root: its package.json `workspaces` are searched for plugins. */
    root: string
    /** A plugin is a workspace package with this file, exporting `const manifest = {name, ...}` as plain data. */
    manifest: string
    /** Every plugin's manifest inlined as `export const <name> = {[pluginName]: manifest}`. */
    manifests?: {name: string, out: string}
    layers: readonly GGPluginGenLayer[]
    /** A package.json whose `dependencies` must list exactly the plugin packages generated files import. */
    dependencies?: {packageJson: string, version: string}
    /** Named in each generated file's header. */
    generatedBy: string
}

interface LoadedPlugin {
    dir: string
    manifest: {name: string}
    pkg: {name: string, exports?: Record<string, string | {import?: string}>}
}

/** Writes per-layer plugin registries from what each plugin package owns: its manifest and its subpath exports. */
export class GGPluginGen {

    private readonly config: GGPluginGenConfig

    public constructor(config: GGPluginGenConfig) {
        this.config = config
    }

    /** Every plugin's manifest, by name. */
    public async manifests(): Promise<{name: string}[]> {
        return (await this.load()).map(p => p.manifest)
    }

    /** Generated content per root-relative path. */
    public async generate(): Promise<Map<string, string>> {
        const plugins = await this.load()
        const files = new Map<string, {imports: string[], bodies: string[]}>()
        const file = (out: string) => {
            const f = files.get(out) ?? {imports: [], bodies: []}
            files.set(out, f)
            return f
        }
        const imported = new Set<string>()
        if (this.config.manifests) {
            const {name, out} = this.config.manifests
            file(out).bodies.push(`export const ${name} = {\n${plugins.map(p => `    ${JSON.stringify(p.manifest.name)}: ${JSON.stringify(p.manifest)},`).join("\n")}\n} as const`)
        }
        for (const layer of this.config.layers) {
            const members: {plugin: string, symbol: string}[] = []
            const f = file(layer.out)
            for (const p of plugins) {
                const symbol = camel(p.manifest.name) + layer.export
                const found = layer.from.filter(s => {
                    const target = exportTarget(p.pkg, s)
                    return target !== undefined && exportsSymbol(join(p.dir, target), symbol)
                })
                if (found.length > 1) throw new Error(`${p.manifest.name}: ${symbol} is exported from ${found.join(" and ")}; ${layer.name} takes one per plugin`)
                if (!found.length) continue
                f.imports.push(`import {${symbol}} from "${p.pkg.name}${found[0].slice(1)}"`)
                imported.add(p.pkg.name)
                members.push({plugin: p.manifest.name, symbol})
            }
            f.bodies.push(`export const ${layer.name} = {${members.map(m => `\n    ${JSON.stringify(m.plugin)}: ${m.symbol},`).join("")}${members.length ? "\n" : ""}}`)
        }
        const out = new Map<string, string>()
        for (const [path, {imports, bodies}] of files) {
            const head = `// Generated by ${this.config.generatedBy} from each plugin's ${this.config.manifest}. Do not edit.\n`
            out.set(path, `${head}${imports.length ? imports.join("\n") + "\n\n" : "\n"}${bodies.join("\n\n")}\n`)
        }
        if (this.config.dependencies) {
            const {packageJson, version} = this.config.dependencies
            out.set(packageJson, this.syncedDependencies(packageJson, version, new Set(plugins.map(p => p.pkg.name)), imported))
        }
        return out
    }

    /** Writes stale files; with `check`, only lists them. Returns the stale paths. */
    public async write(check: boolean): Promise<string[]> {
        const stale: string[] = []
        for (const [path, content] of await this.generate()) {
            const abs = join(this.config.root, path)
            if ((existsSync(abs) ? readFileSync(abs, "utf-8") : "") === content) continue
            stale.push(path)
            if (!check) writeFileSync(abs, content)
        }
        return stale
    }

    /** Runs when `metaUrl` is the script node was started with: writes the files, or with `--check` exits 1 when one is stale. */
    public async cli(metaUrl: string): Promise<void> {
        if (process.argv[1] !== fileURLToPath(metaUrl)) return
        const check = process.argv.includes("--check")
        const stale = await this.write(check)
        if (check) {
            for (const path of stale) console.error(`stale: ${path}`)
            if (stale.length) process.exit(1)
            return
        }
        console.log(stale.length ? `wrote ${stale.join(", ")}` : "plugin registries up to date")
    }

    private syncedDependencies(packageJson: string, version: string, pluginPackages: Set<string>, imported: Set<string>): string {
        const pkg = JSON.parse(readFileSync(join(this.config.root, packageJson), "utf-8")) as {dependencies?: Record<string, string>}
        const deps = Object.entries(pkg.dependencies ?? {}).filter(([name]) => !pluginPackages.has(name) || imported.has(name))
        const missing = [...imported].filter(name => !deps.some(([d]) => d === name)).sort()
        pkg.dependencies = Object.fromEntries([...deps, ...missing.map(name => [name, version])])
        return JSON.stringify(pkg, null, 2) + "\n"
    }

    private async load(): Promise<LoadedPlugin[]> {
        const root = JSON.parse(readFileSync(join(this.config.root, "package.json"), "utf-8")) as {workspaces?: string[]}
        const dirs = (root.workspaces ?? []).flatMap(w => w.endsWith("/*")
            ? readdirSync(join(this.config.root, w.slice(0, -2)), {withFileTypes: true}).filter(e => e.isDirectory()).map(e => join(w.slice(0, -2), e.name))
            : [w])
        const plugins: LoadedPlugin[] = []
        for (const dir of dirs) {
            const manifestFile = join(this.config.root, dir, this.config.manifest)
            if (!existsSync(manifestFile)) continue
            const {manifest} = await import(pathToFileURL(manifestFile).href) as {manifest?: {name?: unknown}}
            if (typeof manifest?.name !== "string") throw new Error(`${relative(this.config.root, manifestFile)}: export const manifest = {name, ...}`)
            const pkg = JSON.parse(readFileSync(join(this.config.root, dir, "package.json"), "utf-8")) as LoadedPlugin["pkg"]
            plugins.push({dir: join(this.config.root, dir), manifest: manifest as {name: string}, pkg})
        }
        plugins.sort((a, b) => a.manifest.name.localeCompare(b.manifest.name))
        for (let i = 1; i < plugins.length; i++) {
            if (plugins[i].manifest.name === plugins[i - 1].manifest.name) throw new Error(`Two plugins are named "${plugins[i].manifest.name}"`)
        }
        return plugins
    }
}

function camel(name: string): string {
    return name.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())
}

function exportTarget(pkg: LoadedPlugin["pkg"], subpath: string): string | undefined {
    const target = pkg.exports?.[subpath]
    return typeof target === "string" ? target : target?.import
}

function exportsSymbol(entry: string, symbol: string): boolean {
    const re = new RegExp(`export ((const|function|async function) ${symbol}\\b|\\{[^}]*\\b${symbol}\\b)`)
    return sourceFiles(dirname(entry)).some(f => re.test(readFileSync(f, "utf-8")))
}

function sourceFiles(dir: string): string[] {
    return readdirSync(dir, {withFileTypes: true}).flatMap(e => {
        const path = join(dir, e.name)
        if (e.isDirectory()) return sourceFiles(path)
        return /\.tsx?$/.test(e.name) && !/\.test\.tsx?$/.test(e.name) ? [path] : []
    })
}
