import {afterEach, describe, expect, it} from "vitest"
import {mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync} from "node:fs"
import {tmpdir} from "node:os"
import {dirname, join} from "node:path"
import {GGPluginGen, type GGPluginGenConfig} from "./GGPluginGen"

let root: string

function write(path: string, content: unknown): void {
    mkdirSync(dirname(join(root, path)), {recursive: true})
    writeFileSync(join(root, path), typeof content === "string" ? content : JSON.stringify(content, null, 2) + "\n")
}

function plugin(dir: string, name: string, files: Record<string, string>): void {
    write(`plugins/${dir}/src/manifest.ts`, `export const manifest = {name: "${name}", hub: {dependsOn: []}} as const\n`)
    const exports: Record<string, {import: string}> = {}
    for (const [subpath, source] of Object.entries(files)) {
        exports[`./${subpath}`] = {import: `./src/${subpath}/index.ts`}
        write(`plugins/${dir}/src/${subpath}/index.ts`, source)
    }
    write(`plugins/${dir}/package.json`, {name: `@app/plugin-${dir}`, exports})
}

const config = (): GGPluginGenConfig => ({
    root,
    manifest: "src/manifest.ts",
    manifests: {name: "MANIFESTS", out: "collection/manifests.gen.ts"},
    layers: [
        {name: "HUB", from: ["./hub"], export: "HubPlugin", out: "collection/hub.gen.ts"},
        {name: "UI", from: ["./vm-ui", "./hub-ui"], export: "ClientPlugin", out: "collection/ui.gen.ts"},
    ],
    dependencies: {packageJson: "collection/package.json", version: "*"},
    generatedBy: "gen.mjs",
})

describe("GGPluginGen", () => {
    afterEach(() => rmSync(root, {recursive: true, force: true}))

    it("writes a record per layer, the manifests, and the collection's plugin dependencies", async () => {
        root = mkdtempSync(join(tmpdir(), "gg-plugin-gen-"))
        write("package.json", {workspaces: ["plugins/*", "collection"]})
        write("collection/package.json", {name: "collection", dependencies: {"@app/plugin-gone": "*", "left-alone": "1.0.0"}})
        plugin("gone", "gone", {})
        plugin("user-keys", "user-keys", {hub: "export const userKeysHubPlugin = {}\n", "hub-ui": "export {userKeysClientPlugin} from \"./plugin\"\n"})
        write("plugins/user-keys/src/hub-ui/plugin.ts", "export const userKeysClientPlugin = {}\n")
        plugin("audit", "audit", {hub: "export const auditHubPlugin = {}\n"})

        const files = await new GGPluginGen(config()).generate()
        expect(files.get("collection/hub.gen.ts")).toBe(`// Generated by gen.mjs from each plugin's src/manifest.ts. Do not edit.
import {auditHubPlugin} from "@app/plugin-audit/hub"
import {userKeysHubPlugin} from "@app/plugin-user-keys/hub"

export const HUB = {
    "audit": auditHubPlugin,
    "user-keys": userKeysHubPlugin,
}
`)
        expect(files.get("collection/ui.gen.ts")).toContain(`import {userKeysClientPlugin} from "@app/plugin-user-keys/hub-ui"`)
        expect(files.get("collection/manifests.gen.ts")).toContain(`    "gone": {"name":"gone","hub":{"dependsOn":[]}},`)
        expect(JSON.parse(files.get("collection/package.json")!).dependencies).toEqual({
            "left-alone": "1.0.0",
            "@app/plugin-audit": "*",
            "@app/plugin-user-keys": "*",
        })
    })

    it("write --check reports stale files without writing; write fixes them", async () => {
        root = mkdtempSync(join(tmpdir(), "gg-plugin-gen-"))
        write("package.json", {workspaces: ["plugins/*", "collection"]})
        write("collection/package.json", {name: "collection"})
        plugin("audit", "audit", {hub: "export const auditHubPlugin = {}\n"})
        const gen = new GGPluginGen(config())

        expect(await gen.write(true)).toEqual(["collection/manifests.gen.ts", "collection/hub.gen.ts", "collection/ui.gen.ts", "collection/package.json"])
        expect(await gen.write(false)).toHaveLength(4)
        expect(await gen.write(true)).toEqual([])
        expect(readFileSync(join(root, "collection/ui.gen.ts"), "utf-8")).toContain("export const UI = {}")
    })

    it("refuses a facet exported from two subpaths", async () => {
        root = mkdtempSync(join(tmpdir(), "gg-plugin-gen-"))
        write("package.json", {workspaces: ["plugins/*"]})
        plugin("x", "x", {"vm-ui": "export const xClientPlugin = {}\n", "hub-ui": "export const xClientPlugin = {}\n"})
        await expect(new GGPluginGen(config()).generate()).rejects.toThrow("x: xClientPlugin is exported from ./vm-ui and ./hub-ui; UI takes one per plugin")
    })
})
